#include<iostream>
using namespace std;
int main(){
    cout<<"Size of int :"<<sizeof(long int)<<endl;
    cout<<"Size of long int :"<<sizeof(long int)<<endl;
    cout<<"Size of short int :"<<sizeof(short)<<endl;
    cout<<"Size of char :"<<sizeof(char)<<endl;
    cout<<"Size of unsigned char :"<<sizeof(unsigned)<<endl;
    cout<<"Size of double double :"<<sizeof(double)<<endl;
    cout<<"Size of double float :"<<sizeof(float)<<endl;
    return 0;
}
